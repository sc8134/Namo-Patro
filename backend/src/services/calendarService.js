// BS 2000-01-01 = AD 1943-04-14
const BS_START_AD = new Date(1943, 3, 14);
const BS_START_YEAR = 2000;

function adToBs(adDate) {
  let totalDays = Math.floor((adDate - BS_START_AD) / (1000 * 60 * 60 * 24));

  let bsYear = BS_START_YEAR;
  let bsMonth = 1;
  let bsDay = 1;

  for (let y = BS_START_YEAR; ; y++) {
    const months = BS_MONTH_DAYS[y];
    if (!months) throw new Error(`BS year ${y} data not available`);
    const yearDays = months.reduce((a, b) => a + b, 0);
    if (totalDays < yearDays) {
      bsYear = y;
      for (let m = 0; m < 12; m++) {
        if (totalDays < months[m]) {
          bsMonth = m + 1;
          bsDay = totalDays + 1;
          break;
        }
        totalDays -= months[m];
      }
      break;
    }
    totalDays -= yearDays;
  }

  return `${bsYear}-${String(bsMonth).padStart(2, "0")}-${String(bsDay).padStart(2, "0")}`;
}

function bsToAd(year, month, day) {
  let totalDays = 0;
  for (let y = BS_START_YEAR; y < year; y++) {
    const months = BS_MONTH_DAYS[y];
    if (!months) throw new Error(`BS year ${y} data not available`);
    totalDays += months.reduce((a, b) => a + b, 0);
  }
  const months = BS_MONTH_DAYS[year];
  if (!months) throw new Error(`BS year ${year} data not available`);
  for (let m = 0; m < month - 1; m++) totalDays += months[m];
  totalDays += day - 1;

  const adDate = new Date(BS_START_AD);
  adDate.setDate(adDate.getDate() + totalDays);
  return adDate.toISOString().split("T")[0];
}

module.exports = { adToBs, bsToAd };
